import resolve from '@rollup/plugin-node-resolve';
import commonjs from '@rollup/plugin-commonjs';
import typescript from '@rollup/plugin-typescript';
import scss from 'rollup-plugin-scss';
import { terser } from 'rollup-plugin-terser';
import fs from 'fs';
import path from 'path';

// Ensure directory exists
const ensureDirectoryExists = (filePath) => {
  const dirname = path.dirname(filePath);
  if (fs.existsSync(dirname)) {
    return true;
  }
  fs.mkdirSync(dirname, { recursive: true });
};

// Shared plugins
const sharedPlugins = [
  resolve({
    extensions: ['.js', '.jsx', '.ts', '.tsx'],
  }),
  commonjs(),
  terser(),
];

export default [
  // Main bundle (Web Components + SCSS) - for npm consumers
  {
    input: 'src/index.ts',
    output: [
      {
        file: 'dist/index.js',
        format: 'cjs',
        sourcemap: true,
        inlineDynamicImports: true,
      },
      {
        file: 'dist/index.esm.js',
        format: 'esm',
        sourcemap: true,
        inlineDynamicImports: true,
      },
    ],
    plugins: [
      ...sharedPlugins,
      typescript({
        tsconfig: './tsconfig.json',
        declaration: true,
        declarationDir: 'dist/types',
      }),
      scss({
        includePaths: ['src/styles'],
        output: function(styles, styleNodes) {
          ensureDirectoryExists('dist/styles/zen-style.css');
          fs.writeFileSync('dist/styles/zen-style.css', styles);
        },
        outputStyle: 'compressed',
      }),
    ]
  },
  // Web Components only bundle (no React) - for documentation/browser use
  {
    input: 'src/index.webcomponents.ts',
    output: [
      {
        file: 'dist/index.webcomponents.js',
        format: 'esm',
        sourcemap: true,
        inlineDynamicImports: true,
      },
    ],
    plugins: [
      ...sharedPlugins,
      typescript({
        tsconfig: './tsconfig.json',
        declaration: false, // Types already generated by main bundle
      }),
      scss({
        includePaths: ['src/styles'],
        output: false, // CSS already generated by main bundle
      }),
    ]
  },
  // Browser bundle - for vanilla JS / <script src=""> usage (ASPX, legacy apps)
  // Exposes everything under window.ZenStyle
  // Usage: <script src="zen-style.js"></script>
  //        ZenStyle.ZenNotificationService.success({ title: 'Saved' });
  {
    input: 'src/index.webcomponents.ts',
    output: {
      file: 'dist/zen-style.js',
      format: 'iife',
      name: 'ZenStyle',
      sourcemap: true,
    },
    plugins: [
      ...sharedPlugins,
      typescript({
        tsconfig: './tsconfig.json',
        declaration: false,
      }),
      scss({
        includePaths: ['src/styles'],
        output: false, // CSS already generated by main bundle
      }),
    ]
  }
]; 